def test_update_loop_state_patches_named_fields(tmp_path: Path):
    store = StateStore(tmp_path)
    store.write(_seed_state())
    store.update_loop_state(
        current_pass="WA2 — Spike",
        current_pass_status="dispatched",
        pending=["A", "B"],
    )
    loaded = store.load()
    assert loaded.loop_state.current_pass == "WA2 — Spike"
    assert loaded.loop_state.current_pass_status == "dispatched"
    assert loaded.loop_state.pending == ["A", "B"]
    # Other fields untouched.
    assert loaded.project.name == "LD"


def test_update_loop_state_rejects_unknown_field(tmp_path: Path):
    store = StateStore(tmp_path)
    store.write(_seed_state())
    with pytest.raises(TypeError, match="unknown field"):
        store.update_loop_state(nonexistent_field=True)


def test_append_decision_appends_in_order(tmp_path: Path):
    store = StateStore(tmp_path)
    store.write(_seed_state())
    store.append_decision(topic="T1", decision="D1", rationale="R1")
    store.append_decision(topic="T2", decision="D2")
    loaded = store.load()
    assert [d.topic for d in loaded.decisions] == ["T1", "T2"]
    assert loaded.decisions[0].rationale == "R1"
    assert loaded.decisions[1].rationale == ""
    # Each decision got an autogenerated ISO date.
    assert loaded.decisions[0].date.endswith("Z")


def test_append_decision_honors_explicit_date(tmp_path: Path):
    store = StateStore(tmp_path)
    store.write(_seed_state())
    store.append_decision(
        topic="T", decision="D", date="2099-01-01T00:00:00Z",
    )
    loaded = store.load()
    assert loaded.decisions[0].date == "2099-01-01T00:00:00Z"


def test_snapshot_is_deep_copy(tmp_path: Path):
    store = StateStore(tmp_path)
    store.write(_seed_state())
    snap = store.snapshot()
    snap.loop_state.pending.append("mutation should not land")
    # Reload from disk — the mutation didn't escape into the file.
    fresh = store.load()
    assert fresh.loop_state.pending == []


def test_update_patches_top_level_fields(tmp_path: Path):
    store = StateStore(tmp_path)
    store.write(_seed_state())
    new_proj = Project(name="LD-renamed", current_pointer="post-update")
    store.update(project=new_proj, working_context_digest="updated")
    loaded = store.load()
    assert loaded.project.name == "LD-renamed"
    assert loaded.project.current_pointer == "post-update"
    assert loaded.working_context_digest == "updated"
    # loop_state untouched.
    assert loaded.loop_state.current_pass == "WA1"


