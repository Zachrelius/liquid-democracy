"""Checkpoint writer tests (WA1 B5) — including the crash-simulation
that guarantees the atomic-rename pattern actually survives mid-write
interruption.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from planner_state.checkpoint import (
    STATE_FILENAME,
    StateCorruptionError,
    StateStore,
)
from planner_state.schema import (
    Decision,
    LoopState,
    PlannerState,
    Project,
    SCHEMA_VERSION,
    SchemaVersionMismatch,
)


def _seed_state() -> PlannerState:
    return PlannerState(
        schema_version=SCHEMA_VERSION,
        project=Project(name="LD", current_pointer="seed pointer"),
        loop_state=LoopState(current_pass="WA1", current_pass_status="in_progress"),
        decisions=[],
        working_context_digest="initial",
    )


# ---------------------------------------------------------------------------
# Round-trip via disk
# ---------------------------------------------------------------------------

def test_write_then_load_round_trips(tmp_path: Path):
    store = StateStore(tmp_path)
    s = _seed_state()
    store.write(s)
    assert store.exists()
    loaded = store.load()
    assert loaded.to_dict() == s.to_dict()


def test_load_or_init_creates_when_absent(tmp_path: Path):
    store = StateStore(tmp_path / "fresh")
    s = store.load_or_init(project_name="Fresh Project")
    assert s.project.name == "Fresh Project"
    assert store.exists()


def test_load_or_init_returns_existing_when_present(tmp_path: Path):
    store = StateStore(tmp_path)
    store.write(_seed_state())
    s = store.load_or_init(project_name="Different Name Should Be Ignored")
    assert s.project.name == "LD"  # the existing project name wins


def test_load_raises_filenotfound_when_no_state(tmp_path: Path):
    store = StateStore(tmp_path / "empty")
    with pytest.raises(FileNotFoundError):
        store.load()


