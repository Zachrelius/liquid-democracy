def test_load_raises_corruption_on_invalid_json(tmp_path: Path):
    store = StateStore(tmp_path)
    # Write garbage directly to the canonical path.
    store.state_dir.mkdir(parents=True, exist_ok=True)
    store.state_path.write_text("not json {{{", encoding="utf-8")
    with pytest.raises(StateCorruptionError, match="not valid JSON"):
        store.load()


def test_load_raises_corruption_on_missing_schema_version(tmp_path: Path):
    store = StateStore(tmp_path)
    store.state_dir.mkdir(parents=True, exist_ok=True)
    store.state_path.write_text('{"project": {"name": "X"}}', encoding="utf-8")
    with pytest.raises(StateCorruptionError, match="schema validation"):
        store.load()


def test_load_propagates_schema_version_mismatch(tmp_path: Path):
    """The version mismatch is its own subclass of ValueError that callers
    can catch to drive a migration. checkpoint.py re-raises it without
    wrapping in StateCorruptionError so the caller can distinguish
    "you need to migrate" from "the file is broken."
    """
    store = StateStore(tmp_path)
    store.state_dir.mkdir(parents=True, exist_ok=True)
    payload = {"schema_version": SCHEMA_VERSION + 1, "project": {"name": "X"}}
    store.state_path.write_text(json.dumps(payload), encoding="utf-8")
    with pytest.raises(SchemaVersionMismatch):
        store.load()


