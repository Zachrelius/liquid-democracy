# Atomicity (the load-bearing test)
# ---------------------------------------------------------------------------

def test_atomic_write_survives_simulated_mid_write_crash(
    tmp_path: Path, monkeypatch
):
    """Simulate the writer crashing AFTER the temp file is written but
    BEFORE the os.replace swap. The prior good state must survive
    unchanged; the partial temp file must not be visible as the
    canonical state.

    Implementation: write a known-good state first, then monkey-patch
    ``os.replace`` to raise mid-call. Attempt a write that mutates a
    field. Assert the on-disk canonical file is STILL the prior good
    one, and the load doesn't see partial data.
    """
    store = StateStore(tmp_path)
    good = _seed_state()
    store.write(good)
    canonical_path = store.state_path
    good_text = canonical_path.read_text(encoding="utf-8")

    mutated = _seed_state()
    mutated.project.current_pointer = "MUTATED — this write will be crashed"

    # Sabotage os.replace. The writer should propagate the exception
    # and clean up any orphan temp.
    original_replace = os.replace

    def _crashing_replace(src, dst):  # type: ignore[no-untyped-def]
        raise RuntimeError("simulated crash between fsync and rename")

    monkeypatch.setattr(os, "replace", _crashing_replace)

    with pytest.raises(RuntimeError, match="simulated crash"):
        store.write(mutated)

    # Restore os.replace so we can read state again.
    monkeypatch.setattr(os, "replace", original_replace)

    # The canonical file is unchanged.
    after_text = canonical_path.read_text(encoding="utf-8")
    assert after_text == good_text, (
        "Canonical state file was modified despite the simulated crash. "
        "The writer must not write directly to the canonical path; the "
        "atomic-rename pattern is broken."
    )
    # A loader sees the prior good state.
    loaded = store.load()
    assert loaded.project.current_pointer == good.project.current_pointer
    # The orphan temp file may or may not exist (depends on which point
    # we crashed at); the writer's exception path tries to clean it. The
    # KEY invariant the test pins is the canonical file being unchanged.


def test_orphan_temp_listed_when_cleanup_fails(tmp_path: Path, monkeypatch):
    """If the writer's cleanup itself fails (e.g., a stat race), the
    orphan temp file is left in place but the canonical state is
    still correct + readable. ``list_orphan_temps`` finds it.
    """
    store = StateStore(tmp_path)
    store.write(_seed_state())

    # Manually drop an orphan temp file in the state dir.
    orphan = store.state_dir / ".planner_state.OOPS.json.tmp"
    orphan.write_text("{}", encoding="utf-8")

    found = store.list_orphan_temps()
    assert orphan in found
    # The canonical state still loads cleanly.
    loaded = store.load()
    assert loaded.project.name == "LD"


def test_temp_files_are_cleaned_on_normal_write(tmp_path: Path):
    """After a successful write there are zero orphan temp files in
    the state dir — the temp file became the canonical file via
    os.replace.
    """
    store = StateStore(tmp_path)
    store.write(_seed_state())
    store.write(_seed_state())  # second write, just to be sure
    assert store.list_orphan_temps() == []
    # And the canonical file is the only .json in the dir.
    json_files = [p for p in store.state_dir.iterdir() if p.suffix == ".json"]
    assert len(json_files) == 1
    assert json_files[0].name == STATE_FILENAME
